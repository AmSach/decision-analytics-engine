class TestSyntheticControlEngine:
    """Validates Synthetic Control convex optimization and counterfactual invariants."""

    def test_convex_weights_and_fit(self):
        # Create synthetic panel: 8 periods, 4 units
        # Unit 1 is treated at time 5 with an artificial +20 lift
        periods = np.arange(1, 9)
        units = ["Unit_A_Treated", "Donor_B", "Donor_C", "Donor_D"]
        records = []

        for t in periods:
            base_trend = 100.0 + 5.0 * t
            for u in units:
                noise = np.random.normal(0, 1.0)
                if u == "Unit_A_Treated":
                    lift = 25.0 if t >= 5 else 0.0
                    val = base_trend + lift + noise
                elif u == "Donor_B":
                    val = base_trend * 0.9 + noise
                elif u == "Donor_C":
                    val = base_trend * 1.1 + noise
                else:
                    val = base_trend * 1.0 + noise

                records.append({"period": t, "unit": u, "sales": val})

        panel_df = pd.DataFrame(records)

        engine = SyntheticControlEngine()
        res = engine.fit_synthetic_control(
            panel_df=panel_df,
            unit_col="unit",
            time_col="period",
            outcome_col="sales",
            treated_unit="Unit_A_Treated",
            intervention_time=5,
        )

        assert res["treated_unit"] == "Unit_A_Treated"
        assert res["pre_intervention_rmse"] >= 0.0
        # Post-intervention lift should be positive (we injected +25)
        assert res["post_intervention_avg_lift"] > 15.0, "Should detect positive causal lift"

        # Check weights invariants: sum(W) = 1.0, W_i >= 0
        weights_sum = sum(d["weight"] for d in res["top_donor_weights"])
        assert np.isclose(weights_sum, 1.0, atol=1e-3), "Donor weights must sum to 1.0"
        for d in res["top_donor_weights"]:
            assert d["weight"] >= 0.0, "Weights must be non-negative"


class TestMarkowitzPortfolioOptimizer:
    """Validates quadratic programming Pareto frontier and VaR invariants."""

    def test_markowitz_budget_and_bounds(self):
        # Create historical returns for 4 marketing channels
        rng = np.random.default_rng(42)
        n_periods = 52  # 52 weeks
        returns_data = {
            "Paid_Search": rng.normal(3.5, 0.4, n_periods),
            "Social_Ads": rng.normal(2.8, 0.6, n_periods),
            "Email_Marketing": rng.normal(4.2, 0.3, n_periods),
            "Referral_Network": rng.normal(3.0, 0.5, n_periods),
        }
        returns_df = pd.DataFrame(returns_data)

        optimizer = MarkowitzCapitalOptimizer(risk_aversion=1.0, max_channel_cap=0.45)
        res = optimizer.fit_optimal_allocation(returns_df, total_budget=150000.0)

        alloc_df = res["allocation_df"]
        total_weight = alloc_df["optimal_weight_pct"].sum()
        total_allocated = alloc_df["allocated_budget"].sum()

        # Invariants
        assert np.isclose(total_weight, 100.0, atol=0.2), "Portfolio weights must sum to 100%"
        assert np.isclose(total_allocated, 150000.0, atol=1.0), "Allocated budget must match total budget"
        assert np.all(alloc_df["optimal_weight_pct"] <= 45.0 + 1e-3), "Weights must respect maximum cap"
        assert np.all(alloc_df["optimal_weight_pct"] >= 0.0), "Weights cannot be negative"
        assert res["risk_adjusted_sharpe"] > 0, "Sharpe ratio should be positive for profitable channels"
        assert res["value_at_risk_95_dollars"] >= 0, "VaR must be non-negative"


class TestUniversalExcelIngestor:
    """Validates schema normalization of messy business Excel and CSV data."""

    def test_messy_csv_harmonization(self, tmp_path):
        # Construct intentionally chaotic business CSV with currency signs and weird names
        messy_csv_path = tmp_path / "messy_client_transactions.csv"
        messy_csv_content = """# Client Monthly Sales Export - Confidential
# Generated by legacy ERP
Client Identifier,Transaction Date,Item Description,Selling Rate,Volume Sold,Total Invoice Amt,Unit Product Cost,Promo Discount
CUST-9821,2023-01-15,Cloud Analytics License,"$1,250.50",2,"$2,501.00","$400.00",10%
CUST-9821,2023-03-10,Cloud Analytics License,"$1,125.00",1,"$1,125.00","$400.00",0%
CUST-4412,2023-02-01,Enterprise Security,"$3,400.00",1,"$3,400.00","$1,100.00",15%
CUST-3310,2023-02-18,SMB Seat,"$45.00",5,"$225.00","$12.00",5%
"""
        messy_csv_path.write_text(messy_csv_content)

        ingestor = UniversalExcelIngestor()
        clean_df = ingestor.ingest_file(messy_csv_path)

        # Invariants check
        required_cols = [
            "customer_id", "order_date", "sku", "effective_price", 
            "quantity", "gross_revenue", "cogs", "gross_margin", "cohort_month"
        ]
        for col in required_cols:
            assert col in clean_df.columns, f"Missing harmonized column: {col}"

        # Check numeric conversions
        assert clean_df["effective_price"].iloc[0] == 1250.50
        assert clean_df["quantity"].iloc[0] == 2
        assert clean_df["gross_revenue"].iloc[0] == 2501.00
        assert clean_df["cogs"].iloc[0] == 400.00
        assert clean_df["gross_margin"].iloc[0] == 2101.00
        assert clean_df["discount_pct"].iloc[0] == 0.10  # 10% normalized to 0.10
        assert clean_df["cohort_month"].iloc[0] == "2023-01"
        assert clean_df["cohort_month"].iloc[1] == "2023-01"  # Same customer repeat purchase
        assert clean_df["cohort_month"].iloc[2] == "2023-02"
